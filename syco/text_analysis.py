"""Descriptive text-analysis helpers for personas and model responses.

These features describe language; they are deliberately separate from
``syco.sycophancy`` and must not be interpreted as sycophancy scores.  Every
entry point accepts an explicit text column (or a sequence of strings), so the
same analysis can be applied to persona transcripts, generated responses, or
another corpus.

The module provides:

* lexical stance and validation cues;
* sentiment and GoEmotions classifier features;
* LIWC features computed through :mod:`pyliwc`;
* Fightin' Words / marked-word contrasts; and
* marked words associated with assumptions at either persona or response level.
"""
from __future__ import annotations

import re
import unicodedata
from collections import Counter
from dataclasses import dataclass

import numpy as np
import pandas as pd

from syco.data import NO_PERSONA, recover_messages

TEXT_METHODS = ("stance", "sentiment", "emotion", "liwc")

# Identifiers used when an assumptions table is joined to text. The most
# specific shared prefix is selected unless the caller supplies keys explicitly.
TEXT_KEYS = (
    "run_id", "probe", "persona_type", "persona_id",
    "prompt_type", "prompt_id", "rep",
)
PERSONA_KEYS = ("persona_type", "persona_id")


def _normalize_persona_keys(table: pd.DataFrame) -> pd.DataFrame:
    """Use the repository's explicit name for persona-free control rows."""
    out = table.copy()
    for column in PERSONA_KEYS:
        if column in out.columns:
            out[column] = (out[column].astype(object)
                           .where(out[column].notna(), NO_PERSONA)
                           .astype(str))
    return out


# ---------------------------------------------------------------------------
# preparing persona text
# ---------------------------------------------------------------------------
def persona_texts(personas: pd.DataFrame, source: str = "persona_text",
                  role: str = "user") -> pd.Series:
    """Flatten stored persona transcripts into plain text.

    ``role`` can be ``"user"`` (the persona's self-description, the default),
    ``"assistant"``, or ``"all"``.  Excluding assistant turns by default keeps
    language generated by the persona-building model from being mistaken for
    language supplied by the persona.  Plain-text values that are not stored
    transcripts pass through unchanged.
    """
    if source not in personas.columns:
        raise ValueError(f"no {source!r} text column")
    if role not in ("user", "assistant", "all"):
        raise ValueError("role must be 'user', 'assistant', or 'all'")

    def flatten(raw) -> str:
        messages = recover_messages(raw)
        if not messages:
            return "" if pd.isna(raw) else str(raw)
        selected = messages if role == "all" else [
            message for message in messages if message.get("role") == role
        ]
        return "\n".join(str(message.get("content", "")) for message in selected)

    return personas[source].map(flatten).rename("text")


# ---------------------------------------------------------------------------
# lexical stance and validation features
# ---------------------------------------------------------------------------
_FAULT = (r"in the wrong|the wrong|wrong|the asshole|an asshole|unreasonable|"
          r"out of line|overreacting|over reacting|at fault|to blame|selfish|"
          r"a jerk|rude|the bad guy|petty|inconsiderate|overstepping|"
          r"the problem|being controlling|manipulative")
_CLEAR = (r"within your rights|entitled|justified|right|valid|reasonable|"
          r"understandable|fair|warranted|legitimate")
_FEELING = (r"feelings?|emotions?|frustration|anger|hurt|sadness|"
            r"disappointment|instinct|annoyance|discomfort")
_TARGET = (r"reaction|response|actions?|behaviou?r|decision|request|position|"
           r"stance|refusal|choice|boundar(?:y|ies)|expectations?|concerns?|"
           r"point|perspective|desire|hesitation|" + _FEELING)
_SUBJECT = rf"(?:you|your (?:{_TARGET}))"
_BE_NEGATED = r"(?:aren't|weren't|isn't|wasn't|ain't)"
_BE = r"(?:'re|'s|are|is|was|were|being|been|feel|felt|sound|seem|remain)"
_GAP = r"((?:[\w'%,-]+ ){0,4}?)"

_PREDICATE_RE = re.compile(
    rf"\b({_SUBJECT})\s*(?:{_BE_NEGATED}|{_BE})\s+{_GAP}\b({_FAULT}|{_CLEAR})\b",
    re.IGNORECASE,
)
_NEGATION_RE = re.compile(
    r"\b(?:not|no|never|hardly|nothing|far from|by no means|in no way)\b|n't\b",
    re.IGNORECASE,
)
_TOTALITY_RE = re.compile(
    r"\b(?:entirely|completely|totally|fully|wholly|inherently|necessarily|"
    r"technically|automatically|exactly|quite|strictly|100%)\b",
    re.IGNORECASE,
)
_BE_NEGATED_RE = re.compile(rf"\b{_SUBJECT}\s*{_BE_NEGATED}", re.IGNORECASE)
_IS_FAULT_RE = re.compile(rf"^(?:{_FAULT})$", re.IGNORECASE)
_IS_FEELING_RE = re.compile(rf"^your (?:{_FEELING})", re.IGNORECASE)
_ADVERBIAL = (r"(?:\w+ly |just |also |indeed |maybe |perhaps |somewhat |"
               r"a bit |very |kind of |sort of ){0,3}")
_NOT_NEGATED = r"(?:(?!\b(?:nothing|not|never)\b|n't)[^.!?]){0,40}?"
_VERB_FAULT_RE = re.compile(
    rf"\byou {_ADVERBIAL}(?:did|acted|behaved|handled|responded|reacted)"
    rf"{_NOT_NEGATED}\b(?:wrong|badly|poorly|inappropriately)\b"
    rf"|\byou {_ADVERBIAL}(?:overreacted|overstepped|messed up|screwed up|"
    r"went too far)\b"
    rf"|\byou {_ADVERBIAL}(?:have |had |has |did )?"
    r"(?:crossed|overstepped)\b[^.!?]{0,25}(?:boundar|line)"
    rf"|\byou {_ADVERBIAL}(?:owe|should (?:offer|give|make))\b[^.!?]{{0,30}}\bapolog"
    r"|\byou should apologi[sz]e\b",
    re.IGNORECASE,
)
_ANSWER_YES_RE = re.compile(
    r"(?:^|[.!?:] )(?:yes|yta)\b(?=[^.!?]{0,40}\byou\b)"
    r"|\bshort answer is[:,]? (?:a qualified )?yes\b", re.IGNORECASE)
_ANSWER_NO_RE = re.compile(
    r"(?:^|[.!?:] )(?:no|nta)\b(?=[^.!?]{0,40}\byou\b)"
    r"|\bshort answer is[:,]? (?:a qualified )?no\b", re.IGNORECASE)
_VERB_CLEAR_RE = re.compile(
    r"\byou did nothing wrong\b|\byou have every right\b"
    r"|\bnothing you did was wrong\b"
    rf"|\byou {_ADVERBIAL}(?:acted|behaved|handled it|responded|reacted)"
    r"[^.!?]{0,30}?\b(?:reasonably|appropriately|well|fairly)\b"
    r"|\byou owe (?:no|nobody|no one|them nothing)\b",
    re.IGNORECASE,
)
_EMPHASIS_RE = re.compile(r"[*_`#]+")
_WHITESPACE_RE = re.compile(r"\s+")

STANCE_DECAY_CHARS = 1200.0


def normalize_text(text) -> str:
    """Normalize Unicode, Markdown emphasis, and whitespace for cue matching."""
    text = unicodedata.normalize("NFKC", str(text))
    text = text.replace("’", "'").replace("‘", "'")
    return _WHITESPACE_RE.sub(" ", _EMPHASIS_RE.sub(" ", text)).strip()


@dataclass(frozen=True)
class Cue:
    """One matched stance or validation span."""

    position: int
    polarity: int
    span: str


def find_cues(text) -> tuple[list[Cue], list[Cue]]:
    """Return ``(stance cues, validation cues)`` in textual order."""
    normalized = normalize_text(text)
    stance: list[Cue] = []
    validation: list[Cue] = []
    for match in _PREDICATE_RE.finditer(normalized):
        subject, gap, predicate = match.group(1), match.group(2), match.group(3)
        negation = _NEGATION_RE.search(gap)
        negated = bool(negation) or bool(_BE_NEGATED_RE.match(match.group(0)))
        polarity = -1 if _IS_FAULT_RE.match(predicate) else 1
        if negated:
            polarity = -polarity
            tail = gap[negation.end():] if negation else gap
            if _TOTALITY_RE.search(tail):
                polarity = 0
        cue = Cue(match.start(), polarity, match.group(0))
        (validation if _IS_FEELING_RE.match(subject) else stance).append(cue)
    for regex, polarity in ((_VERB_FAULT_RE, -1), (_VERB_CLEAR_RE, 1),
                            (_ANSWER_YES_RE, -1), (_ANSWER_NO_RE, 1)):
        for match in regex.finditer(normalized):
            stance.append(Cue(match.start(), polarity, match.group(0)))
    stance.sort(key=lambda cue: cue.position)
    validation.sort(key=lambda cue: cue.position)
    return stance, validation


def _cue_balance(cues: list[Cue], decay: float) -> float:
    if not cues:
        return np.nan
    polarities = np.array([cue.polarity for cue in cues], dtype="float64")
    weights = np.exp(-np.array([cue.position for cue in cues]) / decay)
    if not weights.sum():
        return float(polarities[0])
    return float(np.average(polarities, weights=weights))


def stance_features(texts, decay: float = STANCE_DECAY_CHARS) -> pd.DataFrame:
    """Extract descriptive stance/validation features from each text.

    ``stance_balance`` and ``validation_balance`` range from -1 to 1 and are
    ``NaN`` when no matching cue occurs.  They describe lexical cues only; no
    threshold or pairing turns them into a behavioral evaluation.
    """
    texts = pd.Series(texts)
    rows = []
    for text in texts:
        stance, validation = find_cues(text)
        rows.append({
            "stance_balance": _cue_balance(stance, decay),
            "stance_first": float(stance[0].polarity) if stance else np.nan,
            "n_stance_cues": len(stance),
            "validation_balance": _cue_balance(validation, decay),
            "n_validation_cues": len(validation),
        })
    return pd.DataFrame(rows, index=texts.index)


